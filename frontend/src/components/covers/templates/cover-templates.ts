export function applyTemplateToDesign(
  template: TemplateDefinition,
  currentDesign: CoverDesign,
  bookTitle?: string,
  bookAuthor?: string
): CoverDesign {
  const newLayers = template.layers.map((layer) => {
    const copy = {
      ...layer,
      id: `${layer.id}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 6)}`,
    };
    if (copy.type === 'text') {
      if (copy.role === 'title' && bookTitle) {
        copy.text = bookTitle;
      } else if (copy.role === 'author' && bookAuthor) {
        copy.text = bookAuthor;
      }
    }
    return copy;
  });

  return {
    ...currentDesign,
    background: template.background,
    shade: template.shade,
    artworkId: currentDesign.artworkId,
    layers: newLayers,
  };
}
